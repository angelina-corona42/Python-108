# List Section 
weather = ["Sunny", "Partly Cloudy", "Cloudy", "Rainy"]
print(weather)

print("--------------")

# Access by index
print(weather[2])

print("--------------")

# Replace value
weather.append("Humid")
print(weather)

print("--------------")

# Removing items
weather.remove("Sunny")
print(weather)

print("--------------")

# Length of list 
print(len(weather))

print("--------------")

